//! 应用内更新（开发者 Jan）：下载安装包 → 交给独立的更新进程在客户端退出后完成安装与重启。
//!
//! 运行中的程序无法替换自己的可执行文件（文件被系统占用），因此流程拆成三步：
//! 1. 用 [`crate::client_api`] 的 HTTP 客户端把安装包流式落到临时目录，边下边把进度推给界面；
//! 2. 拉起一个与父进程解绑的 PowerShell 更新进程：等本进程退出 → 静默安装 → 重新启动客户端；
//! 3. 退出客户端进程，其后的安装与重启全部由该子进程完成。
//!
//! 安装包地址由「检查更新」接口下发，因此这里不做接口拼接，只做一次绝对的 GET。
//! 目前只有 Windows 提供该流程：等待进程退出依赖 Windows 的进程查询与安装包静默安装约定，
//! 其它平台由前端退回「浏览器打开下载地址」，行为与旧版一致。
//!
//! 客户端退出后进程已不存在，安装成败无法当场反馈，因此更新进程会把结论落到临时目录的文件里，
//! 由客户端下次启动时经 [`update_take_result`] 读走并提示——否则「点了更新、界面再没回来」
//! 这类问题既没有日志也没有出口。

